# the app uses — same structure as DARK_QSS but with palette colours. This is
# what makes image themes "real themes" rather than just backgrounds.
# ---------------------------------------------------------------------------

def _build_image_theme_qss_from_base(p: dict, base_qss: str) -> str:
    """Build a complete QSS string for an image theme from a base QSS.

    Strategy: take the base QSS (DARK_QSS) verbatim and replace the colour
    values with the theme's palette. This preserves EVERY layout property
    (padding, border-radius, min/max-width, font-size) exactly as the purple
    theme has them — only colours change. This is the only way to keep
    powerBtn at 160x160, navPanel at 18px radius, navBtn at its original
    padding, etc.

    ``base_qss`` is the DARK_QSS string (passed in by the caller to avoid
    importing theme.py at module load time).
    """
    text = p["text"]
    text_on_accent = p["text_on_accent"]
    text_muted = p["text_muted"]
    card_bg = p["card_bg"]
    card_border = p["card_border"]
    card_hover = p["card_hover"]
    accent = p["accent"]
    accent_2 = p["accent_2"]

    qss = base_qss

