"""Catalog of all UI themes — full QSS themes (not just colour overrides).

Each theme defines a complete QSS string that styles EVERY widget in the app
(cards, buttons, inputs, labels, checkboxes, tabs, scrollbars, popups) using
the theme's colour palette. This is what makes them "real themes" rather than
just backgrounds with recoloured cards.

The 3 preset themes (purple / dark / light) reuse the existing QSS strings
defined in theme.py (DARK_QSS / WIN11_DARK_QSS / WIN11_LIGHT_QSS) — those are
already complete and well-tested.

The 7 image themes are generated by ``_build_image_theme_qss(palette)`` from a
palette dict. The generated QSS has the SAME structure as DARK_QSS (every
selector is covered) but with colours drawn from the palette. This guarantees
no widget is left with the wrong colour.

A theme palette contains:
  - text           — primary text colour (used everywhere a label sits on a card)
  - text_on_accent — text colour on accent-coloured buttons (usually white)
  - text_muted     — secondary/muted text (subtitles, hints)
  - card_bg        — background of every card / glass panel
  - card_border    — border of every card
  - card_hover     — hover background for rows / list items
  - accent         — primary accent (selected nav, focused inputs, primaryBtn)
  - accent_2       — secondary accent (gradient end, scrollbar)
  - nav_glow       — rgba colour for the segmented-nav glow effect
  - is_dark        — whether the theme is overall dark (affects shadow opacity)
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import List, Optional


@dataclass(frozen=True)
class Theme:
    id: str
    name_ru: str
    name_en: str
    group: str  # "preset" or "image"
    bg_image: Optional[str]  # filename under ui/assets/themes/, or None
    is_dark: bool
    # Palette (used by _build_image_theme_qss for image themes; preset themes
    # ignore these and use their own pre-built QSS).
    text: str = "#ffffff"
    text_on_accent: str = "#ffffff"
    text_muted: str = "rgba(255,255,255,0.65)"
    card_bg: str = "rgba(20, 12, 45, 220)"
    card_border: str = "rgba(255,255,255,0.14)"
    card_hover: str = "rgba(255,255,255,0.10)"
    accent: str = "#7d52ff"
    accent_2: str = "#c44bff"
    nav_glow: str = "rgba(150, 120, 255, 180)"
    # Full QSS — for preset themes this is empty (we use the pre-built strings
    # from theme.py); for image themes it's generated by _build_image_theme_qss.
    qss: str = ""


