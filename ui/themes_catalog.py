        # Primary text colours (the main "#ece8ff" purple-white used everywhere)
        ("#ece8ff", text),
        ("#f4f1ff", text),
        ("#f2eeff", text),
        ("#eee8ff", text),
        ("#ffffff", text_on_accent),
        ("white", text_on_accent),
        # Muted / secondary text
        ("#cfc7ee", text_muted),
        ("#d7cffb", text_muted),
        ("#c7bfe6", text_muted),
        ("#b9b0e0", text_muted),
        ("#9b93c0", text_muted),
        ("#8a82ad", text_muted),
        # Accent purple → theme accent
        ("#7d52ff", accent),
        ("#9d6bff", accent),
        ("#b14bf0", accent),
        ("#be63f5", accent_2),
        ("#8d66ff", accent_2),
        ("#c44bff", accent_2),
        ("#b172ff", accent),
        ("#d0a3ff", accent_2),
        ("#9d3ee0", accent),
        ("#6d42ef", accent_2),
        # Accent gradient stops (qlineargradient with #b14bf0 → #7d52ff)
        # already covered by the individual colour replacements above.
        # Pink/magenta accents (used in navBtn selected, checkbox checked, etc.)
        ("rgba(255, 126, 226, 0.34)", f"rgba({accent[1:3]},{accent[3:5]},{accent[5:7]}, 0.34)"),
        ("rgba(238, 126, 255, 0.96)", f"rgba({accent[1:3]},{accent[3:5]},{accent[5:7]}, 0.96)"),
