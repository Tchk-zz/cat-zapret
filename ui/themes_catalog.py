        # Card backgrounds (the translucent dark-purple fills)
        ("rgba(16, 8, 56, 0.42)", card_bg),
        ("rgba(16, 8, 56, 0.50)", card_bg),
        ("rgba(18,12,38,0.34)", card_bg),
        ("rgba(34, 16, 92, 0.30)", card_bg),
        ("rgba(14, 7, 48, 0.48)", card_bg),
        ("rgba(12,10,36,0.55)", card_bg),
