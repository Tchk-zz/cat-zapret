        ("#1c1640", card_bg if not card_bg.startswith("rgba") else card_bg),
        ("#211a44", card_bg if not card_bg.startswith("rgba") else card_bg),
        ("#0c0a24", card_bg if not card_bg.startswith("rgba") else card_bg),
        # Borders
        ("rgba(255,255,255,0.14)", card_border),
