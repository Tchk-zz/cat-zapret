# The catalog order is the order themes appear in the dropdown.
THEMES: List[Theme] = [
    _PRESET_PURPLE,
    _PRESET_DARK,
    _PRESET_LIGHT,
    _IMAGE_MIST,
    _IMAGE_AZURE,
    _IMAGE_SNOW,
    _IMAGE_LAVENDER,
    _IMAGE_FOG,
    _IMAGE_SAND,
    _IMAGE_MIDNIGHT,
]


def get_theme(theme_id: str) -> Theme:
    """Return the Theme with the given id, falling back to 'purple'."""
    for t in THEMES:
        if t.id == theme_id:
            return t
    return _PRESET_PURPLE


def theme_ids() -> List[str]:
    return [t.id for t in THEMES]


def is_image_theme(theme_id: str) -> bool:
    """True if the theme uses a photographic background (vs procedural)."""
    t = get_theme(theme_id)
    return t.group == "image" and t.bg_image is not None


def get_theme_qss(theme_id: str, base_qss: dict) -> str:
    """Return the FULL QSS string to apply for the given theme.

    ``base_qss`` is a dict with keys "DARK", "WIN11_DARK", "WIN11_LIGHT"
    pointing at the pre-built QSS strings from theme.py. Preset themes use
    these directly; image themes generate their QSS lazily from DARK_QSS +
    colour substitution (so the layout properties are preserved exactly).
    """
    t = get_theme(theme_id)
    if t.group == "image":
        # If the theme already has a pre-built QSS (from module load time),
        # use it. Otherwise generate it now from the DARK_QSS passed in
        # base_qss. This lazy generation avoids requiring PyQt6 at import
        # time (needed for unit tests).
        if t.qss:
            return t.qss
        # Generate from DARK_QSS + palette.
        palette = {
            "text": t.text,
            "text_on_accent": t.text_on_accent,
            "text_muted": t.text_muted,
            "card_bg": t.card_bg,
            "card_border": t.card_border,
            "card_hover": t.card_hover,
            "accent": t.accent,
            "accent_2": t.accent_2,
            "nav_glow": t.nav_glow,
            "is_dark": t.is_dark,
        }
        return _build_image_theme_qss_from_base(palette, base_qss["DARK"])
    # Preset themes use the pre-built strings from theme.py.
    if t.id == "dark":
        return base_qss["WIN11_DARK"]
    if t.id == "light":
        return base_qss["WIN11_LIGHT"]
    return base_qss["DARK"]
